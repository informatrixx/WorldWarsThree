export function translate(locale, key, variables = {}) {
  const dictionary = translations[locale] ?? translations.de;
  const template = dictionary[key] ?? translations.de[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`));
}

export function playerName(state, playerId, locale = state.config.locale) {
  const player = state.players.find((entry) => entry.id === playerId);
  if (!player) return "—";
  return player.isHuman
    ? translate(locale, "human")
    : player.commanderName ?? translate(locale, "aiPlayer", { number: player.id });
}
